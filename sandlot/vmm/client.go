// Canonical-socket mutual authentication (sandlot ↔ sandvmm). The token is
// generated by the sandlot per VM and delivered to the VMM over an inherited
// fd; it is never argv/env/files. Each connection sends a fresh 32-byte
// challenge and expects token XOR challenge back. A sibling sandvmm that
// binds a fake listener at the victim VM's socket path cannot compute the
// response, so the sandlot aborts before sending a vm.set-fs frame (which
// carries the real HMAC volume name).
const (
	apiAuthMagic   = 0xA5
	apiAuthVersion = 1
	apiAuthLen     = 32
)

// Client talks to the sandvmm API over a Unix socket. The per-request hot
// ops (set-fs, ping) default to the raw control-frame protocol (see
// raw_client.go); VM lifecycle operations always use HTTP/JSON, which the
// sandvmm front dispatcher routes per connection by the first byte on the
// wire.
type Client struct {
	httpClient *http.Client
	socketPath string
	apiToken   []byte

	// rawMu serializes access to rawConn (set-fs runs under the caller's
	// mountMu anyway; this guards a concurrent ping).
	rawMu   sync.Mutex
	rawConn net.Conn
}

// NewClient creates a new VMM API client. apiToken is optional only for
// tests/dev servers that run without --api-token-fd; the sandlot launcher
// always passes the per-VM token.
func NewClient(socketPath string, apiToken ...[]byte) *Client {
	c := &Client{socketPath: socketPath}
	if len(apiToken) > 0 {
		c.apiToken = apiToken[0]
	}
	c.httpClient = &http.Client{
		Transport: &http.Transport{
			DialContext: func(ctx context.Context, _, _ string) (net.Conn, error) {
				return c.dialUnix(ctx)
			},
			// ⑤: keep the Unix-socket connection alive across set-fs/ping
			// calls so each request reuses one UDS connection instead of
			// re-dialing. set-fs runs on every cold attach, and re-dialing
			// the UDS adds avoidable latency. Explicit keep-alive config makes
			// reuse deterministic (Go defaults are permissive but rely on the
			// body being fully drained — see do()).
			DisableKeepAlives:   false,
			MaxIdleConns:        4,
			MaxIdleConnsPerHost: 4,
			IdleConnTimeout:     90 * time.Second,
		},
		Timeout: 30 * time.Second,
	}
	return c
}

// dialUnix connects to the VMM socket and, when a token is configured,
// performs the server-authentication challenge before returning the conn.
func (c *Client) dialUnix(ctx context.Context) (net.Conn, error) {
	conn, err := (&net.Dialer{}).DialContext(ctx, "unix", c.socketPath)
	if err != nil {
		return nil, fmt.Errorf("dial sandvmm: %w", err)
	}
	if len(c.apiToken) == 0 {
		return conn, nil
	}
	if err := c.authenticate(conn); err != nil {
		conn.Close()
		return nil, err
	}
	return conn, nil
}

// authenticate proves the peer knows the per-VM token without sending it:
// response = token XOR challenge, verified byte-for-byte.
func (c *Client) authenticate(conn net.Conn) error {
	if len(c.apiToken) != apiAuthLen {
		return fmt.Errorf("sandvmm API token length %d, want %d", len(c.apiToken), apiAuthLen)
	}
	challenge := make([]byte, apiAuthLen)
	if _, err := rand.Read(challenge); err != nil {
		return fmt.Errorf("sandvmm API auth challenge: %w", err)
	}
	req := make([]byte, 0, 2+apiAuthLen)
	req = append(req, apiAuthMagic, apiAuthVersion)
	req = append(req, challenge...)

	_ = conn.SetDeadline(time.Now().Add(5 * time.Second))
	defer conn.SetDeadline(time.Time{}) // callers install their own deadlines
	if _, err := conn.Write(req); err != nil {
		return fmt.Errorf("sandvmm API auth write: %w", err)
	}
	resp := make([]byte, apiAuthLen)
	if _, err := io.ReadFull(conn, resp); err != nil {
		return fmt.Errorf("sandvmm API auth read: %w", err)
	}
	for i := range resp {
		if resp[i]^challenge[i] != c.apiToken[i] {
			return fmt.Errorf("sandvmm API authentication failed — the socket peer does not know this VM's token (fake/squatted listener, or a VMM spawned without it)")
		}
	}
	return nil
}

// Ping checks if the VMM is alive. Raw transport by default (health probes
// run continuously); HTTP when -setfs-transport=http.
func (c *Client) Ping(ctx context.Context) error {
	if !setFsUseHTTP.Load() {
		return c.rawPing(ctx)
	}
	return c.do(ctx, http.MethodGet, "/api/v1/sandvmm.ping", nil, nil)
}

// CreateVM creates a VM within the running VMM.
func (c *Client) CreateVM(ctx context.Context, config interface{}) error {
	return c.do(ctx, http.MethodPut, "/api/v1/vm.create", config, nil)
}

// BootVM boots the created VM.
func (c *Client) BootVM(ctx context.Context) error {
	return c.do(ctx, http.MethodPut, "/api/v1/vm.boot", nil, nil)
}

// SetFs updates a virtio-fs device's allowed_dirs whitelist at runtime (the
// agent-isolation filter). Raw control-frame transport by default — this
// runs on every cold attach and the HTTP/JSON framing cost is measurable
// there; -setfs-transport=http selects the legacy REST path. An empty
// allowedDirs clears the whitelist (the unmount-time clear).
func (c *Client) SetFs(ctx context.Context, id, tag string, allowedDirs []string, alias string) error {
	if setFsUseHTTP.Load() {
		return c.do(ctx, http.MethodPut, "/api/v1/vm.set-fs", map[string]interface{}{
			"id":  id,
			"tag": tag,
			"backendfs_config": map[string]interface{}{
				"allowed_dirs": allowedDirs,
				"alias":        alias,
			},
		}, nil)
	}
	return c.rawSetFs(ctx, id, tag, allowedDirs, alias)
}

// IsPreviousTenantRefs reports whether a SetFs error is the VMM's reuse
// tripwire: the export being swapped away still holds open handles or
// un-FORGOTTEN inode references, so the swap was refused and the live
// allow-list is untouched. A lying warden unmount reply is the canonical
// cause (processes alive inside the volume pin their root/cwd/files as
// dentries). Classified by the stable message token the VMM's error Display
// carries on BOTH set-fs transports (raw frame and HTTP) — the same
// message-based classification ErrRawProtocolVersion uses; there is no
// richer channel short of a wire error-code bump.
func IsPreviousTenantRefs(err error) bool {
	return err != nil && strings.Contains(err.Error(), "previous-tenant-refs")
}

// AddVsock adds a vsock device to the VM.
//
// The VMM always uses the kernel vhost-vsock backend: the data path is
// offloaded to a kernel worker (shared-memory ring + irqfd), giving zero
// VMEXIT per packet. Routing is by guest CID (via /dev/vhost-vsock), so no
// host-side socket path is needed.
func (c *Client) AddVsock(ctx context.Context, cid uint32) error {
	cfg := map[string]interface{}{
		"cid": uint64(cid),
	}
	return c.do(ctx, http.MethodPut, "/api/v1/vm.add-vsock", cfg, nil)
}

// ShutdownVMM shuts down the VMM process.
func (c *Client) ShutdownVMM(ctx context.Context) error {
	return c.do(ctx, http.MethodPut, "/api/v1/sandvmm.shutdown", nil, nil)
}

func (c *Client) do(ctx context.Context, method, path string, body, result interface{}) error {
	var bodyReader io.Reader
	if body != nil {
		data, err := json.Marshal(body)
		if err != nil {
			return fmt.Errorf("marshal request: %w", err)
		}
		bodyReader = bytes.NewReader(data)
	}

	req, err := http.NewRequestWithContext(ctx, method, "http://localhost"+path, bodyReader)
	if err != nil {
		return err
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := c.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("vmm request %s %s: %w", method, path, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 300 {
		respBody, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("vmm returned %d: %s", resp.StatusCode, string(respBody))
	}

	if result != nil {
		return json.NewDecoder(resp.Body).Decode(result)
	}
	// ⑤: when there is no result to decode, still drain the response body so
	// the underlying UDS connection can be reused by the next request (Go's
	// http.Transport only returns a connection to the idle pool after the body
	// is fully read). Without this, every set-fs/ping call re-dials the UDS,
	// adding avoidable latency on the cold attach path.
	io.Copy(io.Discard, resp.Body)
	return nil
}
