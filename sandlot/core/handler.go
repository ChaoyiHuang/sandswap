// vmMonitorState holds the crash-detection and health-probe state for a VM.
// Extracted from VMState for cohesion: this is monitoring/lifecycle concern,
// not business state. Fresh VMs have a per-VM goroutine blocking on cmd.Wait()
// (the sole reaper of the child zombie); when it returns it closes waitDone.
// Re-adopted VMs are watched by the centralized pidfdMonitor (no per-VM
// goroutine, no waitDone) — the monitor fires onExit directly.
//
// destroyVMByID/handleVMDied set `destroying` so the crash path (monitorVMCore
// for fresh VMs, the monitor's onExit for re-adopted) knows the exit was
// intentional and teardown is owned by destroy, not handleVMDied.
type vmMonitorState struct {
	waitDone   chan struct{} // fresh VMs only: closed when the cmd.Wait goroutine returns
	mu         sync.Mutex
	destroying bool
	// Health-probe failure count. The heartbeat probe (VMMemStats) dials a
	// FRESH short-lived warden connection per VM per heartbeat (independent of
	// the exec slot pool, so a long sync exec doesn't block the probe). N
	// consecutive failures ⇒ the VM's warden/guest is hung ⇒ handleVMDied.
	// Reset to 0 on a successful probe. Guarded by mu.
	//
	// Every VM in h.vms answered at least one probe before registration
	// (CreateVerifiedVM checks synchronously), so this verdict only ever fires
	// on a warden that WORKED and then went silent — a real hang. A guest that
	// never finishes booting is destroyed by its creator instead, and never
	// becomes visible here.
	consecutiveProbeFailures int
	// Last failure's error text, for the per-episode WARN policy: the first
	// failure and every CHANGED error are logged, repeats of the same error
	// are not (the destroy line carries the final error anyway). Guarded by mu.
	lastProbeErrMsg string
}

// VMState tracks a running microVM.
// pendingMount is one in-flight cold-mount generation.
type pendingMount struct {
	sandfsID    string
	volumePath  string
	alias       string
	gen         int64
	agentID     string
	templateRef string
	volumeMode  string
	volumeEpoch string
}

type VMState struct {
	VM      *vmm.RunningVM
	Cfg     vmm.Config
	Volumes map[string]struct{} // set of volumePaths currently mounted (bind mount or overlay)
	// mountIdentity is the warden-side identity recorded for the CURRENT
	// mount: "L5:<random nonce>:<volume basename>". The nonce is generated by
	// this process on the cold mount and is unknowable by an out-of-band
	// mount RPC racing the switch (the L5 confused-deputy fix). Guarded by
	// mountMu; "" = no nonce recorded (legacy/test fallback: the basename).
	mountIdentity     string
	mountIdentityPath string
	// pendingMount is the generation a cold mount is currently establishing.
	// A second cold request for the same sandfs/volume JOINS it instead of
	// minting a new alias: a per-generation alias is not idempotent, so two
	// set-fs calls would retire the first generation and turn the warden's
	// duplicate-mount fold into a spurious failure. Guarded by mountMu.
	pendingMount *pendingMount
	// mountAliasBySandfs / mountPathBySandfs record the generation identity
	// with the BINDING, not with the VM's current mount: an unmount must name
	// the alias that belongs to THIS sandfs, otherwise a stale binding could
	// present the new tenant's identity and tear down the live mount.
	// Guarded by mountMu; cleared with the binding.
	mountAliasBySandfs map[string]string
	mountPathBySandfs  map[string]string
	// mountCount counts successful cold mount generations; mountCountedGen
	// makes the increment once per generation (joiners share it). Guarded by
	// mountMu (count is atomic for shouldRecycle's lock-free read).
	mountCount      atomic.Uint64
	mountCountedGen int64
	// distinctAgents bounds how many different agents this VM serves over its
	// lifetime. Guarded by mountMu.
	distinctAgents map[string]struct{}
	// mountEpochBySandfs records the volume epoch for the binding. An unmount
	// whose epoch differs names a superseded generation and must not tear down
	// the current mount. Guarded by mountMu; cleared with the binding.
	mountEpochBySandfs map[string]string
	SpecID             string // VM spec identifier: "small", "medium", "large" (empty = default)

	// useCount: number of commands served since this VM was created — one per
	// successful exec or file op (warm or cold; app-level failures like ENOENT
	// count, the command still ran). When it reaches recycleMaxUses the VM is
	// destroyed+recreated on its next unmount to reset warden heap
	// fragmentation + kernel slab baseline.
	useCount atomic.Uint64

	// memAvail/memTotal: last reported guest memory stats from heartbeat probes.
	// Used by shouldRecycle() to decide whether to destroy+recreate on unmount.
	// Atomic so shouldRecycle can read without state.mu (avoids a data race
	// with VMMemStats writes).
	memAvail atomic.Uint64 // guest MemAvailable (bytes)
	memTotal atomic.Uint64 // guest MemTotal (bytes)

	// pendingDestroy is set by ResizePool when the VM is busy but excess to the
	// pool target. On the next unmount, the VM is destroyed instead of returned
	// to CLEAN. This ensures pool scale-down eventually completes even when all
	// VMs are IN_USE at resize time. Cleared by a subsequent ResizePool (which
	// recalculates from scratch) or when the VM is destroyed.
	// Atomic: written by destroyIdleVMs/markBusyForDestroy (no lock
	// or under mountMu only) and read by handleUnmountRootfs (under mountMu).
	pendingDestroy atomic.Bool

	// dirtyDestroyScheduled is a once-guard for scheduleDirtyVMDestroy: two
	// teardown paths can independently decide the same VM is dirty (e.g. the
	// restart-resumed redialWarden racing ResetSurvivorsToClean). Without the
	// CAS, both spawn destroyAndReplaceVM, and its replacement-count check can
	// run before either createPoolVM registers, over-provisioning the pool to
	// target+1. CAS false→true by the first caller; the VM object is discarded
	// after destroy, so no reset is needed.
	dirtyDestroyScheduled atomic.Bool

	// activeBgExecs counts background execs started on this VM that haven't yet
	// reported done/killed. Atomic so destroyIdleVMs can read it without any
	// lock probing.
	// Incremented on async_exec start; decremented ONCE per exec on its first
	// done/killed report (bgDoneReported dedups — the warden keeps answering
	// "done" for every later poll of a finished exec until unmount); reset to 0
	// on unmount (cgroup.kill clears all bg execs). Used by destroyIdleVMs to
	// PREFER destroying sync-handled VMs (activeBgExecs==0, free up fast) over
	// async-handled VMs (activeBgExecs>0, preserve background work).
	activeBgExecs atomic.Int64

	// bgDoneReported is the per-VM set of background exec IDs whose completion
	// has already been counted into activeBgExecs. Without it, a second poll of
	// a done exec (the warden's registry keeps the entry until unmount) or a
	// KillExec followed by a StatusExec "killed" decrements a SECOND time — the
	// underflow-clamp only stops negatives, so the eaten count belongs to OTHER
	// live execs and the VM gets destroyed as "sync-handled" while background
	// work still runs. Cleared together with activeBgExecs at unmount (the
	// guest registry is cleared by the same cgroup.kill). Guarded by bgDoneMu.
	bgDoneMu       sync.Mutex
	bgDoneReported map[string]struct{}

	// mountMu serializes mount/unmount/switch operations on this VM (the
	// Volumes map, the virtio-fs allowed_dirs swap, and the warden mount RPC).
	// It deliberately does NOT cover the exec wait: parallel sync execs borrow
	// their own warden connection from wpool, so a long exec no longer blocks
	// unmount bookkeeping, FileOps, or sibling execs. Held across the whole
	// OP_UNMOUNT RPC so warm execs observe a consistent "mounted" state until
	// the warden finishes the teardown (the warden's MOUNT_GATE then orders
	// the teardown against its own in-flight execs).
	mountMu sync.Mutex

	// wp is the per-VM warden connection pool: one in-flight request per
	// connection (the raw vsock protocol has no correlation ID), up to
	// execSlots connections. Lazily initialized on first acquire so all VM
	// creation paths (pool, on-demand, re-adopt) share one code path.
	wp     *wardenPool
	wpOnce sync.Once

	// execSlots is the pool size for this VM, fixed at creation from the
	// spec's exec_slots (0/unknown = 1). A spec hot-reload therefore takes
	// effect on newly created VMs; existing VMs pick it up on their recycle
	// cycle. Read at pool init; atomic so it can be set post-construction by
	// re-adopt (which learns the spec asynchronously).
	execSlots atomic.Int64

	// inFlight counts warden RPCs in flight on this VM (sync exec, file op,
	// status, kill, mount placeholder). This is the busy signal for pool
	// destroy/recycle classification — it replaces the old execMu.TryLock
	// probing and never blocks the caller.
	inFlight atomic.Int64

	// mountGen increments on every Volumes invalidation (unmount, old-volume
	// swap, reset-to-clean), under mountMu. A cold combined RPC reads it before
	// dispatch and re-checks it under mountMu before recording Volumes: if it
	// changed mid-flight, the VM was unmounted/switched while the RPC ran and
	// the result must not be recorded as a live mount. Without this, an
	// unmount landing between the RPC response and the mark would resurrect a
	// stale Volumes entry and permanently poison the warm path.
	mountGen atomic.Int64

	// tapIfindex is the kernel ifindex of this VM's TAP (the egress identity
	// binding region's slot key). 0 = unresolved/offline (never publishes).
	// Set once by initBindingSlot at registration; TAP ifindexes are stable
	// for the device's lifetime.
	tapIfindex atomic.Uint32

	// bindEpoch increments per identity publish on this attachment, so a VM
	// reused across agents never shares a binding generation with its
	// previous tenant. Seeded from wall clock at registration (epochSeed) so
	// generations never repeat across sandlot restarts or ifindex recycling.
	// Written only under mountMu.
	bindEpoch atomic.Uint64

	// bindAgentID/bindSandfsID are the identity of the last SUCCESSFUL
	// publish on this attachment. Used to collapse same-identity re-entry
	// (parallel cold execs on one sandfs before the first marks Volumes)
	// into the existing generation instead of churning epoch + stamp per
	// exec. Guarded by mountMu; cleared by revoke and by publish failure.
	bindAgentID, bindSandfsID string

	vmMonitorState // embedded: crash-detection and health-probe state
}

// wardenPoolFor returns the VM's lazily-initialized warden connection pool.
func (vm *VMState) wardenPoolFor() *wardenPool {
	vm.wpOnce.Do(func() {
		limit := int(vm.execSlots.Load())
		if limit < 1 {
			limit = 1
		}
		vm.wp = newWardenPool(limit)
	})
	return vm.wp
}

// countBgDoneOnce reports whether THIS completion report for execID should
// decrement activeBgExecs: true exactly once per exec (the first done/killed
// report), false for every repeat — the warden keeps a finished exec's entry
// until unmount and answers every later poll with done/killed again.
func (vm *VMState) countBgDoneOnce(execID string) bool {
	vm.bgDoneMu.Lock()
	defer vm.bgDoneMu.Unlock()
	if vm.bgDoneReported == nil {
		vm.bgDoneReported = make(map[string]struct{})
	}
	if _, ok := vm.bgDoneReported[execID]; ok {
		return false
	}
	vm.bgDoneReported[execID] = struct{}{}
	return true
}

// resetBgExecTracking zeroes the active-background-exec counter AND the
// once-set that dedups completion reports. Callers are the unmount paths whose
// in-guest cgroup.kill clears the whole bg registry — both sides restart empty
// together.
func (vm *VMState) resetBgExecTracking() {
	vm.bgDoneMu.Lock()
	vm.bgDoneReported = make(map[string]struct{})
	vm.bgDoneMu.Unlock()
	vm.activeBgExecs.Store(0)
}

// Handler processes VMCommand messages from the gateway.
type Handler struct {
	mu  sync.RWMutex
	vms map[string]*VMState
	// bindings is the sandfs_id -> vm_id delegation map plus the per-sandfs
	// affinity hints and the per-VM occupancy index (delegation: the gateway
	// addresses workloads by sandfs_id and sandlot resolves to the VM locally).
	// Invariant B (one sandfs -> one VM; one VM -> one sandfs) is enforced by
	// the store's per-sandfs shard plus claimVM. It is deliberately NOT under
	// mu: the cold-switch hot path binds/unbinds once per mount and unmount,
	// and a global write lock there convoys VM selection (see
	// bindings_store.go).
	bindings *bindingStore

	// --- state.json flusher + sandbox-dir reconcile (state_flush.go) ---
	//
	// stateDirty is the set of VM ids whose reuse accounting changed since the
	// last drain. Mount paths insert O(1); the single flusher goroutine swaps
	// the set out and writes. Replaces the per-mount `go persistRuntime` whose
	// goroutine-per-cold-mount spawn and event-time snapshots made high
	// cold-mount rates pay one write per event and let two concurrent mounts'
	// writes land out of order. Guarded by stateDirtyMu.
	stateDirty   map[string]struct{}
	stateDirtyMu sync.Mutex
	// stateKick wakes the flusher for semantic changes (a NEW distinct agent
	// on a VM). Cap 1: a kick while one is pending coalesces — the dirty set
	// already carries the change. Never sent blocking.
	stateKick chan struct{}
	// stateFlusherStop closes exactly once in StopStateFlusher; the loop does
	// a final drain before exiting. stateFlusherOnce guards the close.
	stateFlusherStop chan struct{}
	stateFlusherOnce sync.Once
	stateFlusherWG   sync.WaitGroup
	// orphanDirSeen carries the first-sight time of every unrecognized sandbox
	// dir, so ReconcileSandboxDirs only removes dirs that stayed ownerless for
	// orphanDirGrace (never a VM that is mid-creation). Guarded by
	// orphanDirMu; bounded by the on-disk dir count.
	orphanDirSeen map[string]time.Time
	orphanDirMu   sync.Mutex

	vmmCfg  vmm.Config
	nextCID uint32          // auto-incrementing guest vsock CID counter
	cidMax  uint32          // upper bound for CID allocation (0 = no limit)
	cidFree []uint32        // free-list of released CIDs available for reuse
	cidUsed map[uint32]bool // CIDs claimed by re-adopted VMs (skip in allocation)

	// readoptPending marks re-adopted survivors whose guest rootfs mount has
	// not yet been PROVEN released (redialWarden unmounts them asynchronously;
	// a survivor whose cleanup could not run may still hold a pre-crash
	// mount). Read once at process start by mayHoldUnreleasedMounts so the
	// runner can re-anchor TOLERATING when mounts may be held without a
	// persisted disconnect record — otherwise a dead gateway plus unreachable
	// DNS would leave the probe loop's heartbeats resetting the warden
	// countdowns forever and the mounts would never be released. Guarded by mu.
	//
	// It is ALSO the selection gate: resolveVMForMount never hands a
	// pending VM a new mount. A survivor is unselectable until its cleanup
	// succeeds (clearReadoptPending) or the VM is destroyed.
	readoptPending map[string]struct{}

	// volIDs caches verified (sandfs_id, volume_path) stamp bindings for the
	// cold-mount identity check. Bounded LRU keyed by SHA-256; lazily
	// initialized (volidentity.go) so test handlers need no wiring.
	volIDs     *volIDCache
	volIDsOnce sync.Once

	// memLedger is the guest-memory admission ledger. Every VM creation reserves
	// its spec's memory here BEFORE anything is allocated, and holds the
	// reservation until the VM is destroyed. See mem_ledger.go for why
	// reserving by spec size (rather than admitting against MemAvailable alone)
	// is what actually prevents overcommit.
	memLedger *memLedger

	// Resource-shortage alarm throttle (see alarmResourceShortage).
	alarmMu           sync.Mutex
	lastResourceAlarm time.Time

	net    vmm.NetworkProvider // outbound networking (embedded mode only; nil in boxout mode)
	vm     VMLifecycleManager  // VM lifecycle operations (replaces direct vmm.Launch, h.net.*, overlay calls)
	client *rpc.Client
	logger *log.Logger

	// Quarantine for VMs whose destroy could not be confirmed. The VM was
	// already removed from h.vms and its CID/memory reservation deliberately
	// NOT released; the orphan may still hold an old virtio-fs filter, so new
	// VM creation is refused until a retry confirms the process is dead. See
	// quarantine.go.
	quarantineMu         sync.Mutex
	quarantine           map[string]*quarantinedVM
	quarantineRetryDelay time.Duration // 0 = default (5s); tests shorten it

	// opDebug gates every per-op success-path Printf (mount/exec/unmount/
	// file_op warm AND cold, VM boot/ready). A node serving thousands of
	// ops/sec would flood the log with them and put an unbuffered stdout
	// write on the response path (the response is sent after the handler
	// returns). Normal completions print nothing by default; debugOp checks
	// the flag BEFORE fmt.Sprintf so a disabled gate costs one atomic load.
	// Enabled by `sandlot -debug`. Error/warning lines are unconditional.
	opDebug atomic.Bool

	// testDialFn, when set (handler tests), overrides the pool's vsock dial so
	// extra slots come from in-process fakes. Nil in production.
	testDialFn func(cid uint32, timeout time.Duration) (*warden.Client, error)
	// testProbeFn, when set (monitor tests), overrides the probe loop's
	// per-VM warden MemStats call so sweep-abandonment can be driven
	// deterministically. Nil in production.
	testProbeFn func(cid uint32) (avail, total uint64, err error)
	pidfdM      *pidfdMonitor // centralized epoll watch of re-adopted VM sandvmm pids (nil if pidfd unsupported)

	// metrics collects node-level scheduling signals ,
	// sampled by a 1s tick + exec events, reported in the heartbeat.
	metrics    *NodeMetricsCollector
	cpuSampler hostCPUSampler

	// memStats is the cached per-VM guest memory snapshot, maintained by the
	// independent probe loop (StartProbeLoop) - NOT probed on demand. The probe
	// loop runs during CONNECTED and TOLERATING (decoupled from the gateway
	// stream) so warden last_heartbeat (the single countdown anchor) stays fresh
	// — the warden countdown then fires only on a real cleanup overrun, not on
	// gateway-loss (tolerance-first). VMMemStats() (called by the
	// gateway-bound heartbeat) just reads this cache.
	memStats   map[string]*pb.VmMemInfo
	memStatsMu sync.RWMutex

	// SandboxRoot is the on-disk root of per-VM sandbox directories.
	// Defaults to "/run/sandswap/vm". When instance.id is set, the root
	// becomes "<base-dir>/<instance-id>/vm/" for path isolation.
	SandboxRoot string

	// overlayCache caches parsed ref entries keyed by template ref string.
	// Avoids repeated file reads + JSON parsing on repeated cold-path calls for
	// the same template. Template refs are immutable after creation, so the
	// cache never needs invalidation.
	overlayCache map[string]*overlayRefEntry
	overlayMu    sync.RWMutex

	// mountedOverlays tracks volumePaths that have a host-side overlay mount
	// (populated by ensureReadonlyOverlayMounted, removed by
	// cleanupHostOverlay), mapped to the template ref each mount serves —
	// the swap-staleness fast path compares it with the expected ref carried
	// by every mount command ("" = flat volume / unknown). The daily reaper
	// iterates ONLY this map — not the shared filesystem — so it scales to
	// O(this node's mounts) instead of O(all SandFS on shared storage).
	// Restored from /proc/self/mountinfo at startup via
	// restoreMountedOverlaysFromMountinfo (merged with the persisted
	// overlays.json ref map) and persisted on every change. Guarded by overlayMu.
	mountedOverlays map[string]string

	// Recycle config (hot-reloadable via UpdateRecycleConfig).
	// Destroy+recreate a VM on its next unmount when it has served
	// recycleMaxUses sandfs or its guest MemAvailable drops below
	// min() of the enabled memory thresholds (see shouldRecycle).
	// Zero disables that trigger.
	recycleMaxUses    atomic.Int64
	recycleMaxMounts  atomic.Int64
	maxDistinctAgents atomic.Int64
	affinityVMs       atomic.Int64
	// Batch VM lifecycle concurrency. Set at startup from
	// concurrency.vm_create / vm_destroy (default 5 / 10); restart-required,
	// so a config reload never changes them.
	vmCreateConcurrency  atomic.Int64
	vmDestroyConcurrency atomic.Int64
	recycleMemPercent    atomic.Int64 // e.g. 10 = 10% of MemTotal
	recycleMemAbsMB      atomic.Int64 // e.g. 100 = 100 MiB absolute threshold

	// minIdleFloorFracBps (min-idle floor dampener): the min-idle floor as
	// basis points (frac*10000). The effective per-spec pool target is
	// target + max(1, floor(frac*target)) when > 0, so a spare CLEAN VM is
	// pre-created to absorb bursts and reduce zero-clean frequency (which would
	// otherwise trigger load shedding). Read by ResizePool/ReconcilePool.
	// 0 = disabled. Stored as int64 (basis points) for atomic access.
	// Hot-reloadable via UpdateRecycleConfig.
	minIdleFloorFracBps atomic.Int64

	// poolSpecs tracks the desired pool target per spec name (e.g. {"small":2, "medium":3}).
	// Set by ResizePool on config hot-reload; used to determine how many VMs of each
	// spec should exist. Empty means no pool management (on-demand only).
	poolSpecs map[string]int

	// specResources tracks the resource parameters (vcpus, memory) for each spec name.
	// Set by ResizePool and SetPoolSpecs; used by destroyAndReplaceVM to create
	// replacement VMs with the correct resource configuration.
	specResources map[string]SpecResources

	// nextPoolSeq is a monotonically increasing counter used to generate unique
	// pool VM IDs (e.g., "pool-medium-5"). Using a counter instead of the current
	// VM count avoids ID collisions when VMs are destroyed and new ones are created
	// with the same spec — the old VM's TAP device / sandbox dir may still be
	// cleaning up when the new VM is launched, causing "Device or resource busy".
	nextPoolSeq int

	// poolVMIDPrefix is an optional prefix for pool VM IDs (e.g., "sl1-").
	// Set via SetPoolVMIDPrefix for multi-instance deployments so that VM IDs
	// are unique across sandlot instances on the same host. Guards against
	// gateway-side byID collisions when multiple sandlots serve one gateway.
	poolVMIDPrefix string

	// createMu serializes the VM-creation section (createPoolVM calls) across
	// ResizePool scale-up, ReconcilePool (60s self-heal ticker), and
	// destroyAndReplaceVM (unmount-triggered replacement). It prevents two
	// concurrent creators from both observing a shortfall and double-creating
	// the same VM. Narrow lock: wraps only createPoolVM, not the whole
	// ResizePool. Lock order: createMu is independent of h.mu - acquire h.mu
	// (RLock) to read target/specResources, release it, THEN take createMu to
	// create. Never hold createMu while waiting on a warden RPC.
	createMu sync.Mutex

	// OnPoolChanged is called after ResizePool completes, so the caller can
	// trigger an immediate heartbeat to reconcile the gateway's pool view.
	// If nil, no notification is sent (gateway learns via the periodic heartbeat).
	OnPoolChanged func()

	// probeMu guards the warden-probe loop lifecycle (StartProbeLoop /
	// StopProbeLoop). The loop runs during CONNECTED and TOLERATING — its
	// OP_MEM_STATS heartbeats keep each VM's warden countdown anchor fresh.
	// StopProbeLoop cancels it on entering CLEANING so the countdowns can fire
	// as the last-resort mount release; StartProbeLoop restarts it on reconnect.
	probeMu sync.Mutex
	// probeLoop is non-nil while a probe loop is running. A TOKEN (not a bool)
	// so a Stop+Start pair cannot be confused by the old goroutine's shutdown —
	// see StartProbeLoop's comment.
	probeLoop *probeLoopToken

	// logCapOnce guards the guest console-log cap loop (StartGuestLogCapLoop):
	// exactly one loop per process, started once and never stopped — the cap
	// check is lifecycle-independent (a CLEANING/CLEAN VM's logs still must
	// not grow unbounded).
	logCapOnce sync.Once

	// readoptWG tracks in-flight re-adopt cleanups (redialWarden goroutines:
	// each re-adopted survivor unmounts its pre-restart guest mount). The
	// reconnect path waits on it (WaitReadoptCleanup) BEFORE announcing itself,
	// upholding the reconnect-clean invariant: the gateway's OnConnect must
	// never see a node whose survivor still holds a stale mount — without the
	// wait, the startup NodeHello can beat the async unmount by milliseconds
	// (or by seconds against a slow warden).
	readoptWG sync.WaitGroup

	// bind is the optional egress identity binding region (nil = enabler
	// disabled). Set once via SetBindRegion at startup. All core writes go
	// through the helpers in binding.go.
	bind *bindreg.Region
}

// NewHandler creates a command handler. vm manages VM lifecycle (must be
// non-nil). netProvider provisions outbound networking per VM (may be nil in
// boxout mode where boxout owns networking).
// A centralized pidfdMonitor is started to watch re-adopted VM sandvmm exits
// via a single epoll loop (scales to tens of thousands of VMs with zero idle
// CPU). If pidfd/epoll is unavailable the monitor is nil and re-adopted VMs
// fall back to per-VM ping-poll.
func NewHandler(client *rpc.Client, defaultCfg vmm.Config, vm VMLifecycleManager, netProvider vmm.NetworkProvider, logger *log.Logger) *Handler {
	if logger == nil {
		logger = log.Default()
	}
	// vm may be nil in embedded mode (chicken-and-egg: embeddedManager needs
	// a Handler ref, Handler needs a VMLifecycleManager). The caller must call
	// SetVMLifecycle before using any vm operations. A nil vm is only valid
	// during initialization; all vm method calls guard against nil.
	h := &Handler{
		vms:             make(map[string]*VMState),
		bindings:        newBindingStore(),
		vmmCfg:          defaultCfg,
		net:             netProvider,
		vm:              vm,
		client:          client,
		logger:          logger,
		overlayCache:    make(map[string]*overlayRefEntry),
		mountedOverlays: make(map[string]string),
		SandboxRoot:     defaultSandboxRoot,
		cidFree:         make([]uint32, 0),
		cidUsed:         make(map[uint32]bool),
		readoptPending:  make(map[string]struct{}),
		memLedger:       newMemLedger(readHostMemTotalMB(), nil),
		metrics:         NewNodeMetricsCollector(),
		memStats:        make(map[string]*pb.VmMemInfo),
	}
	h.recycleMaxMounts.Store(10000)
	h.maxDistinctAgents.Store(300)
	h.affinityVMs.Store(3)
	h.stateDirty = make(map[string]struct{})
	h.stateKick = make(chan struct{}, 1)
	h.stateFlusherStop = make(chan struct{})
	h.orphanDirSeen = make(map[string]time.Time)
	h.vmCreateConcurrency.Store(5)
	h.vmDestroyConcurrency.Store(10)
	if mon, err := newPidfdMonitor(logger); err != nil {
		logger.Printf("pidfd monitor unavailable (%v); re-adopted VMs will use per-VM ping-poll", err)
	} else {
		h.pidfdM = mon
		go mon.run()
	}

	return h
}

