// vmBoundToLocked reports whether vmID is bound to any sandfs. O(1) via the
// store's per-VM index; it takes only that VM's shard, NOT the Handler mutex,
// so callers may hold h.mu (any mode) while calling it.
func (h *Handler) vmBoundToLocked(vmID string) bool {
	_, ok := h.bindings.vmBound(vmID)
	return ok
}

// atRecycleThreshold reports whether either dual counter has reached its
// configured limit (0 = disabled; validation rejects other negatives). Used by
// cold selection to prefer VMs below the bound; the counter read is atomic and
// lock-free.
func (h *Handler) atRecycleThreshold(st *VMState) bool {
	if st == nil {
		return false
	}
	if maxUses := h.recycleMaxUses.Load(); maxUses > 0 && st.useCount.Load() >= uint64(maxUses) {
		return true
	}
	if maxMounts := h.recycleMaxMounts.Load(); maxMounts > 0 && st.mountCount.Load() >= uint64(maxMounts) {
		return true
	}
	return false
}

// resolveVMForMount returns the VM to serve sandfsID. If the sandfs is already
// bound to a live VM, that VM is returned (warm path - the caller decides warm
// vs cold by whether the volume is mounted). Otherwise a CLEAN VM (unbound,
// alive, not pendingDestroy, spec-satisfying) is picked and bound (cold path).
// Returns nil when no suitable VM is available (caller should return an error so
// the gateway retries on another node).
func (h *Handler) resolveVMForMount(sandfsID, minSpec, agentID string) *VMState {
	// Fast path: an existing binding is returned read-only. The store lookup
	// takes one shard; the VM-table read takes h.mu.RLock, which the binding
	// path never blocks (nothing on this path takes the write lock), so
	// concurrent mounts do not queue behind each other.
	if vmID, ok := h.bindings.lookup(sandfsID); ok {
		h.mu.RLock()
		st := h.vms[vmID]
		_, pending := h.readoptPending[vmID]
		h.mu.RUnlock()
		if st != nil && !st.pendingDestroy.Load() && !pending {
			return st
		}
		// Stale binding: the VM is gone, being destroyed, or re-adopting. Drop
		// the binding and (for a pendingDestroy VM still holding the guest
		// mount) schedule its destroy after selection.
		h.bindings.removeIfOwner(sandfsID, vmID)
		// Only a pendingDestroy VM is abandoned (it still holds the guest
		// mount, and it is excluded from selection so nothing else would ever
		// unmount it). A re-adopting survivor keeps its VM: the binding is
		// dropped here and the VM becomes selectable again once its cleanup is
		// verified.
		if st != nil && st.pendingDestroy.Load() {
			h.scheduleDirtyVMDestroy(st, "sandfs re-homed away from a pendingDestroy VM with a live mount")
		}
	}

	// The selection is optimistic: snapshot, pick, then claim + install. Two
	// concurrent requests for the same sandfs both reach the claim; the store's
	// sandfs shard lets exactly one install, and the loser releases its VM
	// claim and joins the winner. Two requests for different sandfs cannot
	// claim the same VM (claimVM is the per-VM exclusivity point).
	const attempts = 4
	for attempt := 0; attempt < attempts; attempt++ {
		// Re-check the fast path between attempts: a concurrent request for the
		// same sandfs may have published the binding while this one lost a VM
		// claim. Joining it is always correct (the winner's mountMu/pendingMount
		// handshake folds the duplicate), and it is the only way a loser can
		// finish when every candidate VM was claimed by other sandfs.
		if vmID, ok := h.bindings.lookup(sandfsID); ok {
			h.mu.RLock()
			st := h.vms[vmID]
			_, pending := h.readoptPending[vmID]
			h.mu.RUnlock()
			if st != nil && !st.pendingDestroy.Load() && !pending {
				return st
			}
			h.bindings.removeIfOwner(sandfsID, vmID)
			if st != nil && st.pendingDestroy.Load() {
				h.scheduleDirtyVMDestroy(st, "sandfs re-homed away from a pendingDestroy VM with a live mount")
			}
		}

		// Selection runs under the read lock, in place: no per-mount copy of the
		// VM table (an affinity hit costs O(len(affinity)) lookups, and only an
		// affinity miss scans the pool — the same cost profile as before). The
		// lock is a read lock, so concurrent mounts never queue behind each
		// other; only VM lifecycle writes (cold path) can wait briefly.
		var best, overThreshold, fullClean *VMState
		bestRank := -1
		h.mu.RLock()
		affinity := h.bindings.affinityOf(sandfsID)
		selectable := func(st *VMState) (clean, allows bool, ok bool) {
			if st == nil || st.pendingDestroy.Load() {
				return false, false, false
			}
			if _, pending := h.readoptPending[st.VM.ID]; pending {
				return false, false, false
			}
			if _, bound := h.bindings.vmBound(st.VM.ID); bound {
				return false, false, false
			}
			if st.inFlight.Load() > 0 {
				return false, false, false
			}
			if !st.mountMu.TryLock() {
				return false, false, false
			}
			clean = len(st.Volumes) == 0 && st.pendingMount == nil
			allows = h.distinctAgentAllowedLocked(st, agentID)
			st.mountMu.Unlock()
			return clean, allows, true
		}
		// Affinity: prefer the VMs this sandfs used recently, in order.
		for _, vmID := range affinity {
			st := h.vms[vmID]
			clean, allows, ok := selectable(st)
			if !ok || !clean || !allows {
				continue
			}
			if minSpec != "" && !specSatisfies(st.SpecID, minSpec) {
				continue
			}
			if h.atRecycleThreshold(st) {
				if overThreshold == nil {
					overThreshold = st
				}
				continue
			}
			best = st
			bestRank = specRank(st.SpecID)
			break
		}
		if best == nil {
			for _, st := range h.vms {
				clean, allows, ok := selectable(st)
				if !ok || !clean {
					continue
				}
				if minSpec != "" && !specSatisfies(st.SpecID, minSpec) {
					continue
				}
				if !allows {
					if fullClean == nil {
						fullClean = st
					}
					continue
				}
				if h.atRecycleThreshold(st) {
					if overThreshold == nil {
						overThreshold = st
					}
					continue
				}
				r := specRank(st.SpecID)
				if best == nil || r < bestRank {
					best = st
					bestRank = r
				}
			}
		}
		if best == nil && overThreshold != nil {
			best = overThreshold
		}
		h.mu.RUnlock()
		if best == nil {
			if fullClean != nil {
				// Every clean candidate is at its distinct-agent cap and does not
				// already serve this agent: recycle one so the next request gets a
				// fresh VM instead of reusing it beyond the cap. Policy recycle,
				// not a failure; counted in /stats.
				if h.scheduleDirtyVMDestroy(fullClean, "distinct-agent cap reached; recycling a clean VM") && h.metrics != nil {
					h.metrics.RecordRecycleTrigger()
				}
			}
			return nil
		}

		// Claim the VM (per-VM exclusivity), then publish the binding. If the
		// sandfs was bound concurrently, release our claim and join the winner.
		if !h.bindings.claimVM(best.VM.ID, sandfsID) {
			continue // lost the VM to another sandfs; re-snapshot and retry
		}
		cur, installed := h.bindings.install(sandfsID, best.VM.ID)
		if installed {
			// The VM may have been destroyed between the snapshot and the
			// claim: the old implementation held the global write lock across
			// selection AND binding, so that window did not exist. Re-check
			// liveness under the read lock; a dead VM's binding is dropped and
			// the claim released, and the next attempt picks a live VM.
			h.mu.RLock()
			live := h.vms[best.VM.ID] == best
			_, radopt := h.readoptPending[best.VM.ID]
			h.mu.RUnlock()
			if live && !best.pendingDestroy.Load() && !radopt {
				return best
			}
			h.bindings.removeIfOwner(sandfsID, best.VM.ID)
			h.bindings.releaseVM(best.VM.ID, sandfsID)
			continue
		}
		h.bindings.releaseVM(best.VM.ID, sandfsID)
		if cur != "" {
			h.mu.RLock()
			other := h.vms[cur]
			h.mu.RUnlock()
			if other != nil {
				return other
			}
			continue
		}
	}
	return nil
}

// distinctAgentAllowedLocked reports whether a new mount by agentID fits this
// VM's distinct-agent budget. Caller holds mountMu.
func (h *Handler) distinctAgentAllowedLocked(st *VMState, agentID string) bool {
	limit := h.maxDistinctAgents.Load()
	if limit <= 0 || agentID == "" {
		return true
	}
	if _, ok := st.distinctAgents[agentID]; ok {
		return true
	}
	return int64(len(st.distinctAgents)) < limit
}

// recordAffinityLocked moves vmID to the front of the sandfs's recent-VM list
// and caps it at affinityVMs. The list lives in the sandfs shard, so the call
// takes no Handler mutex.
func (h *Handler) recordAffinityLocked(sandfsID, vmID string) {
	h.bindings.recordAffinity(sandfsID, vmID, int(h.affinityVMs.Load()))
}

// specSatisfies reports whether the VM's spec satisfies the required spec
// (a larger spec always satisfies a smaller one; unknown = default medium).
func specSatisfies(vmSpecID, requiredSpecID string) bool {
	return specRank(vmSpecID) >= specRank(requiredSpecID)
}

func specRank(specID string) int {
	switch specID {
	case "small":
		return 0
	case "medium":
		return 1
	case "large":
		return 2
	}
	return 1 // unknown specs default to medium
}

// SpecCapacityList returns per-spec CLEAN/total VM counts + 60s tail-window
// extrema for heartbeat reporting (delegation: the gateway picks a NODE by spec
// capacity; the window extrema drive the hard floor).
func (h *Handler) SpecCapacityList() []*pb.SpecCapacity {
	// Tail-window extrema from the metrics collector (min_clean, zero_count).
	windows := h.metrics.Snapshot().SpecWindows

	h.mu.RLock()
	defer h.mu.RUnlock()
	total := make(map[string]uint32)
	clean := make(map[string]uint32)
	for _, st := range h.vms {
		if st == nil || st.pendingDestroy.Load() {
			continue
		}
		spec := st.SpecID
		if spec == "" {
			spec = "medium" // default spec
		}
		total[spec]++
		if !h.vmBoundToLocked(st.VM.ID) {
			clean[spec]++
		}
	}
	out := make([]*pb.SpecCapacity, 0, len(total))
	for spec, t := range total {
		sc := &pb.SpecCapacity{SpecId: spec, Clean: clean[spec], Total: t}
		if w, ok := windows[spec]; ok {
			sc.MinCleanWindow = w[0]
			sc.ZeroCleanCount = w[1]
		} else {
			// Window not yet filled (node bootstrap) -> treat as full headroom so
			// MinCleanWindow==0 is unambiguous (a real 60s hit-zero).
			sc.MinCleanWindow = t
		}
		out = append(out, sc)
	}
	return out
}

// TickMetrics samples the current pool/host state into the metrics collector.
// Called every ~1s by the serve loop
func (h *Handler) TickMetrics() {
	h.mu.RLock()
	totalVMs := uint32(len(h.vms))
	activeSandfs := uint32(h.bindings.len())
	var bg uint32
	specCleans := make(map[string]uint32)
	specHasVM := make(map[string]bool)
	for _, st := range h.vms {
		if st == nil {
			continue
		}
		bg += uint32(st.activeBgExecs.Load())
		spec := st.SpecID
		if spec == "" {
			spec = "medium"
		}
		specHasVM[spec] = true
		if !h.vmBoundToLocked(st.VM.ID) && !st.pendingDestroy.Load() {
			specCleans[spec]++
		}
	}
	// Represent every spec with live VMs (clean defaults to 0 if all busy), so
	// the 60s window records clean=0 correctly.
	for spec := range specHasVM {
		if _, ok := specCleans[spec]; !ok {
			specCleans[spec] = 0
		}
	}
	h.mu.RUnlock()
	h.metrics.Tick(totalVMs, activeSandfs, bg, specCleans, h.cpuSampler.sample(), readHostMemAvailMB())
}

