// mayHoldUnreleasedMounts reports whether any tracked VM may still hold a
// sandfs mount that is not confirmed released — either this process mounted a
// volume and hasn't unmounted it (non-empty Volumes), or a re-adopted
// survivor's cleanup has not yet proven the guest clean (readoptPending:
// bindings do not survive a restart, so a survivor's mount state is unknown
// until redialWarden's unmount succeeds). Used at runner start to re-anchor
// the tolerance clock when a crash while CONNECTED left no disconnect record
// (see initialCleanupState).
//
// Volumes is guarded by each VM's mountMu: readopt's async survivor cleanups
// (redialWarden, tracked by readoptWG) may still be swapping it when the
// serve loop starts, so an unsynchronized read is a data race. Snapshot the
// VMStates under h.mu, then lock each mountMu — never hold h.mu across
// mountMu (the unmount paths take h.mu WHILE holding mountMu; the reverse
// order here would invert that and can deadlock).
func (h *Handler) mayHoldUnreleasedMounts() bool {
	h.mu.RLock()
	pending := len(h.readoptPending) > 0
	states := make([]*VMState, 0, len(h.vms))
	for _, vm := range h.vms {
		states = append(states, vm)
	}
	h.mu.RUnlock()
	if pending {
		return true
	}
	for _, vm := range states {
		vm.mountMu.Lock()
		mounted := len(vm.Volumes) > 0
		vm.mountMu.Unlock()
		if mounted {
			return true
		}
	}
	return false
}

// markReadoptPending records a re-adopted survivor whose guest mount state is
// not yet proven released. Call BEFORE launching the survivor's redialWarden
// cleanup, or a fast cleanup could clear the mark before it lands.
func (h *Handler) markReadoptPending(vmID string) {
	h.mu.Lock()
	h.readoptPending[vmID] = struct{}{}
	h.mu.Unlock()
}

// clearReadoptPending records that a survivor's guest mount has been proven
// released (its redialWarden unmount succeeded). Entries for survivors that
// are destroyed instead of cleaned up stay marked: "destroyed" is not the same
// as "proven released", and the mark is only ever read at process start (the
// warden countdown releases any mount on a doomed VM moments later).
func (h *Handler) clearReadoptPending(vmID string) {
	h.mu.Lock()
	delete(h.readoptPending, vmID)
	h.mu.Unlock()
}

