// ProcessCommand handles a single VMCommand from the gateway.
func (h *Handler) ProcessCommand(ctx context.Context, cmd *pb.VMCommand) {
	var resp *pb.CommandResponse

	switch action := cmd.Action.(type) {
	case *pb.VMCommand_UnmountRootfs:
		resp = h.handleUnmountRootfs(ctx, cmd, action.UnmountRootfs)
	case *pb.VMCommand_MountRootfsAndExecute:
		resp = h.handleMountRootfsAndExecute(ctx, cmd, action.MountRootfsAndExecute)
	case *pb.VMCommand_StatusExec:
		resp = h.handleStatusExec(ctx, cmd, action.StatusExec)
	case *pb.VMCommand_KillExec:
		resp = h.handleKillExec(ctx, cmd, action.KillExec)
	case *pb.VMCommand_FileOp:
		resp = h.handleFileOp(ctx, cmd, action.FileOp)
	case *pb.VMCommand_CleanupOverlay:
		resp = h.handleCleanupOverlay(ctx, cmd, action.CleanupOverlay)
	default:
		resp = &pb.CommandResponse{
			CommandId: cmd.CommandId,
			Success:   false,
			Error:     fmt.Sprintf("unknown command type: %T", cmd.Action),
		}
	}

	if c := h.clientOr(); c != nil {
		if err := c.SendResponse(resp); err != nil {
			h.logger.Printf("failed to send response: %v", err)
		}
	} else {
		h.logger.Printf("no gateway client; dropping response for command %s", resp.CommandId)
	}
}

