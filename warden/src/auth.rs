#[inline(always)]
fn ch(x: u32, y: u32, z: u32) -> u32 {
    (x & y) ^ (!x & z)
}
#[inline(always)]
fn maj(x: u32, y: u32, z: u32) -> u32 {
    (x & y) ^ (x & z) ^ (y & z)
}
#[inline(always)]
fn big_sigma0(x: u32) -> u32 {
    x.rotate_right(2) ^ x.rotate_right(13) ^ x.rotate_right(22)
}
#[inline(always)]
fn big_sigma1(x: u32) -> u32 {
    x.rotate_right(6) ^ x.rotate_right(11) ^ x.rotate_right(25)
}
#[inline(always)]
fn small_sigma0(x: u32) -> u32 {
    x.rotate_right(7) ^ x.rotate_right(18) ^ (x >> 3)
}
#[inline(always)]
fn small_sigma1(x: u32) -> u32 {
    x.rotate_right(17) ^ x.rotate_right(19) ^ (x >> 10)
}

fn compress(state: &mut [u32; 8], block: &[u8; 64]) {
    let mut w = [0u32; 64];
    for (i, chunk) in block.chunks_exact(4).enumerate() {
        w[i] = u32::from_be_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]);
    }
    for i in 16..64 {
        w[i] = small_sigma1(w[i - 2])
            .wrapping_add(w[i - 7])
            .wrapping_add(small_sigma0(w[i - 15]))
            .wrapping_add(w[i - 16]);
    }

    let mut a = state[0];
    let mut b = state[1];
    let mut c = state[2];
    let mut d = state[3];
    let mut e = state[4];
    let mut f = state[5];
    let mut g = state[6];
    let mut h = state[7];

    for i in 0..64 {
        let t1 = h
            .wrapping_add(big_sigma1(e))
            .wrapping_add(ch(e, f, g))
            .wrapping_add(K[i])
            .wrapping_add(w[i]);
        let t2 = big_sigma0(a).wrapping_add(maj(a, b, c));
        h = g;
        g = f;
        f = e;
        e = d.wrapping_add(t1);
        d = c;
        c = b;
        b = a;
        a = t1.wrapping_add(t2);
    }

    state[0] = state[0].wrapping_add(a);
    state[1] = state[1].wrapping_add(b);
    state[2] = state[2].wrapping_add(c);
    state[3] = state[3].wrapping_add(d);
    state[4] = state[4].wrapping_add(e);
    state[5] = state[5].wrapping_add(f);
    state[6] = state[6].wrapping_add(g);
    state[7] = state[7].wrapping_add(h);
}

impl Sha256 {
    pub fn new() -> Self {
        Sha256 {
            state: IV,
            buf: [0u8; 64],
            buf_len: 0,
            total_len: 0,
        }
    }

    pub fn update(&mut self, mut data: &[u8]) {
        self.total_len = self.total_len.wrapping_add(data.len() as u64);
        if self.buf_len > 0 {
            let need = 64 - self.buf_len;
            let take = need.min(data.len());
            self.buf[self.buf_len..self.buf_len + take].copy_from_slice(&data[..take]);
            self.buf_len += take;
            data = &data[take..];
            if self.buf_len == 64 {
                let block = self.buf;
                compress(&mut self.state, &block);
                self.buf_len = 0;
            }
        }
        let mut chunks = data.chunks_exact(64);
        for chunk in &mut chunks {
            let block: &[u8; 64] = chunk.try_into().expect("chunks_exact(64)");
            compress(&mut self.state, block);
        }
        let rem = chunks.remainder();
        if !rem.is_empty() {
            self.buf[..rem.len()].copy_from_slice(rem);
            self.buf_len = rem.len();
        }
    }

    pub fn finish(mut self) -> [u8; 32] {
        // Padding: 0x80, zeros, then the 64-bit bit length. One or two blocks.
        let bit_len = self.total_len.wrapping_mul(8);
        let mut tail = [0u8; 128];
        let rem = self.buf_len;
        tail[..rem].copy_from_slice(&self.buf[..rem]);
        tail[rem] = 0x80;
        let tail_len = if rem < 56 { 64 } else { 128 };
        tail[tail_len - 8..tail_len].copy_from_slice(&bit_len.to_be_bytes());
        for chunk in tail[..tail_len].chunks_exact(64) {
            let block: &[u8; 64] = chunk.try_into().expect("chunks_exact(64)");
            compress(&mut self.state, block);
        }
        let mut out = [0u8; 32];
        for (i, word) in self.state.iter().enumerate() {
            out[i * 4..i * 4 + 4].copy_from_slice(&word.to_be_bytes());
        }
        out
    }
}

impl Default for Sha256 {
    fn default() -> Self {
        Self::new()
    }
}

/// HMAC-SHA256 (RFC 2104) over a list of message parts, without allocating.
pub fn hmac_sha256_parts(key: &[u8], parts: &[&[u8]]) -> [u8; 32] {
    let mut block_key = [0u8; 64];
    if key.len() > 64 {
        let digest = {
            let mut h = Sha256::new();
            h.update(key);
            h.finish()
        };
        block_key[..32].copy_from_slice(&digest);
    } else {
        block_key[..key.len()].copy_from_slice(key);
    }

    let mut ipad = [0x36u8; 64];
    let mut opad = [0x5cu8; 64];
    for i in 0..64 {
        ipad[i] = block_key[i] ^ 0x36;
        opad[i] = block_key[i] ^ 0x5c;
    }

    let inner = {
        let mut h = Sha256::new();
        h.update(&ipad);
        for part in parts {
            h.update(part);
        }
        h.finish()
    };

    let mut h = Sha256::new();
    h.update(&opad);
    h.update(&inner);
    h.finish()
}

/// HMAC-SHA256 over one contiguous message. Kept for tests/tools; the hot path
/// uses `hmac_sha256_parts` to avoid building a concatenated buffer.
#[allow(dead_code)]
pub fn hmac_sha256(key: &[u8], msg: &[u8]) -> [u8; 32] {
    hmac_sha256_parts(key, &[msg])
}

/// Constant-time comparison: the loop's result is a pure function of every
/// input byte pair, and `black_box` keeps the compiler from replacing it with
/// an early-exit memcmp.
pub fn ct_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    core::hint::black_box(diff) == 0
}

/// Tag over the fixed request header. Binds the version, op, body length, the
/// nonce and the body-field MAC, so a captured tag cannot be moved to a
/// different op, frame shape or authenticated payload.
pub fn request_tag(
    key: &[u8],
    version: u8,
    op: u8,
    body_len: u32,
    nonce: &[u8; 16],
    body_mac: &[u8; 32],
) -> [u8; 32] {
    let vop = [version, op];
    let blen = body_len.to_be_bytes();
    hmac_sha256_parts(key, &[REQUEST_LABEL, &vop, &blen, nonce, body_mac])
}

/// Domain label for the op-specific body-field MAC. The main header tag
/// authenticates this MAC (it is part of the tagged header), so a frame that
/// does not hold the per-VM session key — a host-local process, a replayed or
/// rewritten frame from outside the guest — cannot change a mount
/// identity/target field. The key lives in guest memory, so a compromised
/// guest KERNEL can read it and forge frames; kernel compromise is a boundary
/// breach, not an in-sandbox event (see the threat model). stdout/stderr/
/// command payloads stay unhashed.
pub const BODY_MAC_LABEL: &[u8] = b"sandswap.warden.body.v1";
/// Domain label for the response's mounted-identity MAC.
pub const MOUNTED_MAC_LABEL: &[u8] = b"sandswap.warden.mounted.v1";

/// MAC over the op-specific body fields that must not be editable without the
/// per-VM session key (a host-side peer or a forged frame; a compromised guest
/// kernel holds the key): the warm-op mounted-volume identity, or the cold
/// mount op's (alias, mount_point, volume_mode). The message is
/// `label || nonce || op || len0 || f0 || len1 || f1 || len2 || f2`, with
/// absent fields encoded as zero length — the sandlot implements the same
/// bytes (sandlot/warden/client.go).
pub fn body_mac(key: &[u8], nonce: &[u8; 16], op: u8, fields: &[&[u8]]) -> [u8; 32] {
    let opb = [op];
    let empty: &[u8] = &[];
    let f0 = fields.first().copied().unwrap_or(empty);
    let f1 = fields.get(1).copied().unwrap_or(empty);
    let f2 = fields.get(2).copied().unwrap_or(empty);
    let l0 = (f0.len() as u32).to_be_bytes();
    let l1 = (f1.len() as u32).to_be_bytes();
    let l2 = (f2.len() as u32).to_be_bytes();
    hmac_sha256_parts(
        key,
        &[BODY_MAC_LABEL, nonce, &opb, &l0, f0, &l1, f1, &l2, f2],
    )
}

/// MAC over the response's mounted-volume identity bytes, bound to the request
/// nonce. Carried after the mounted segment because the header tag (which
/// authenticates lengths) must be verified before any body is read.
pub fn mounted_tag(key: &[u8], nonce: &[u8; 16], mounted: &[u8]) -> [u8; 32] {
    hmac_sha256_parts(key, &[MOUNTED_MAC_LABEL, nonce, mounted])
}

/// Tag over the fixed response header, bound to the request nonce so a
/// response can only be accepted by the client that issued that request.
#[allow(clippy::too_many_arguments)]
pub fn response_tag(
    key: &[u8],
    nonce: &[u8; 16],
    version: u8,
    code: u8,
    exit_code: u8,
    stdout_len: u32,
    stderr_len: u32,
    exec_duration_ns: u64,
    mounted_len: u32,
) -> [u8; 32] {
    let vce = [version, code, exit_code];
    let sl = stdout_len.to_be_bytes();
    let el = stderr_len.to_be_bytes();
    let dur = exec_duration_ns.to_be_bytes();
    let ml = mounted_len.to_be_bytes();
    hmac_sha256_parts(
        key,
        &[
            RESPONSE_LABEL,
            nonce,
            &vce,
            &sl,
            &el,
            &dur,
            &ml,
        ],
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(bytes: &[u8]) -> String {
        let mut s = String::with_capacity(bytes.len() * 2);
        for b in bytes {
            s.push_str(&format!("{:02x}", b));
        }
        s
    }

    #[test]
    fn sha256_nist_vectors() {
        let abc = {
            let mut h = Sha256::new();
            h.update(b"abc");
            h.finish()
        };
        assert_eq!(
            hex(&abc),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        let empty = Sha256::new().finish();
        assert_eq!(
            hex(&empty),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        let long = {
            let mut h = Sha256::new();
            h.update(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq");
            h.finish()
        };
        assert_eq!(
            hex(&long),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        // Split updates must equal one-shot hashing.
        let mut split = Sha256::new();
        split.update(b"abcdbcdecdefdefgefghfghighij");
        split.update(b"hijkijkljklmklmnlmnomnopnopq");
        assert_eq!(hex(&split.finish()), hex(&long));
    }

    #[test]
    fn hmac_sha256_rfc4231_vectors() {
        // Case 1
        let key = [0x0bu8; 20];
        assert_eq!(
            hex(&hmac_sha256(&key, b"Hi There")),
            "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7"
        );
        // Case 2
        assert_eq!(
            hex(&hmac_sha256(b"Jefe", b"what do ya want for nothing?")),
            "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"
        );
        // Case 6: key longer than the block size.
        let key6 = [0xaau8; 131];
        assert_eq!(
            hex(&hmac_sha256(
                &key6,
                b"Test Using Larger Than Block-Size Key - Hash Key First"
            )),
            "60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54"
        );
    }

    #[test]
    fn tags_bind_every_field() {
        let key = [0x11u8; 32];
        let nonce = [0x22u8; 16];
        let bm = [0x33u8; 32];
        let base = request_tag(&key, 2, 3, 128, &nonce, &bm);
        assert_eq!(base, request_tag(&key, 2, 3, 128, &nonce, &bm));
        assert_ne!(base, request_tag(&key, 2, 4, 128, &nonce, &bm));
        assert_ne!(base, request_tag(&key, 2, 3, 129, &nonce, &bm));
        assert_ne!(base, request_tag(&key, 3, 3, 128, &nonce, &bm));
        assert_ne!(base, request_tag(&key, 2, 3, 128, &[0x23u8; 16], &bm));
        assert_ne!(base, request_tag(&[0x12u8; 32], 2, 3, 128, &nonce, &bm));
        // The body-field MAC is part of the tagged header: moving it changes
        // the tag even though the main fields are identical.
        assert_ne!(base, request_tag(&key, 2, 3, 128, &nonce, &[0x34u8; 32]));
        assert_ne!(
            base,
            response_tag(&key, &nonce, 2, 3, 128, 0, 0, 0, 0)
        );

        // The op-specific body MAC binds every field and their boundaries.
        let one = body_mac(&key, &nonce, 1, &[b"gen0", b"/mnt/rootfs", b"flat"]);
        assert_eq!(one, body_mac(&key, &nonce, 1, &[b"gen0", b"/mnt/rootfs", b"flat"]));
        assert_ne!(one, body_mac(&key, &nonce, 2, &[b"gen0", b"/mnt/rootfs", b"flat"]));
        assert_ne!(one, body_mac(&key, &nonce, 1, &[b"gen1", b"/mnt/rootfs", b"flat"]));
        assert_ne!(one, body_mac(&key, &nonce, 1, &[b"gen0", b"/mnt/rootfX", b"flat"]));
        assert_ne!(one, body_mac(&key, &nonce, 1, &[b"gen0", b"/mnt/rootfs", b"flat2"]));
        // Length-prefixing means ("ab","c") and ("a","bc") differ.
        assert_ne!(
            body_mac(&key, &nonce, 1, &[b"ab", b"c"]),
            body_mac(&key, &nonce, 1, &[b"a", b"bc"])
        );
        // Mounted identity content is bound.
        assert_ne!(
            mounted_tag(&key, &nonce, b"sf-aaa"),
            mounted_tag(&key, &nonce, b"sf-bbb")
        );
        assert_ne!(
            mounted_tag(&key, &nonce, b"sf-aaa"),
            mounted_tag(&key, &[0x23u8; 16], b"sf-aaa")
        );

        assert!(ct_eq(&base, &base));
        let mut tampered = base;
        tampered[31] ^= 1;
        assert!(!ct_eq(&base, &tampered));
        assert!(!ct_eq(&base, &base[..31]));
    }

    /// Cross-language pin: the sandlot's Go implementation
    /// (sandlot/warden/client_test.go) asserts the same bytes for the same
    /// inputs. If either side's field order, label, or key padding drifts, one
    /// of the two tests fails before a deploy can.
    #[test]
    fn cross_language_tag_vectors() {
        let key = [0x11u8; 32];
        let mut nonce = [0u8; 16];
        for (i, b) in nonce.iter_mut().enumerate() {
            *b = i as u8;
        }
        let body_mac_value = [0x44u8; 32];
        assert_eq!(
            hex(&request_tag(&key, 2, 1, 0, &nonce, &body_mac_value)),
            "a29e407ff863cad30227edba10159711ec1b9e74894fc25ee7577f2df0610a7d"
        );
        assert_eq!(
            hex(&body_mac(&key, &nonce, 1, &[b"gen0", b"/mnt/rootfs", b"flat"])),
            "30570df5bb0e09b601716dd1ce020cf1a86af46f05c963bec5d654e9641ab2b2"
        );
        assert_eq!(
            hex(&mounted_tag(&key, &nonce, b"sf-abc")),
            "dfc0589f316104b3cf7070a0d17800b1bec5b24f36c3e625741873033991d923"
        );
        assert_eq!(
            hex(&response_tag(&key, &nonce, 1, 0, 0, 5, 7, 123456789, 9)),
            "aa2103e82c4ca35abd951492965daf74fbd4080420a117f5ed0cac9d54769eab"
        );
    }

    /// Hot-path cost report. Run with:
    ///   cargo test --release auth_tag_hot_path_cost -- --nocapture
    /// The assertion bound is deliberately loose (it is a regression alarm,
    /// not a latency SLA); the printed number is what the release notes quote.
    #[test]
    fn auth_tag_hot_path_cost() {
        let key = [0x5au8; 32];
        let nonce = [0x33u8; 16];
        let iters: u32 = 200_000;
        let start = std::time::Instant::now();
        let mut acc = 0u8;
        let bm = [0x44u8; 32];
        for i in 0..iters {
            let t = request_tag(&key, 2, 3, i, &nonce, &bm);
            acc ^= t[0];
        }
        let r = start.elapsed();
        let t2 = {
            let mut acc2 = 0u8;
            let start2 = std::time::Instant::now();
            for i in 0..iters {
                let t = response_tag(&key, &nonce, 2, 0, 0, i, 0, i as u64, 0);
                acc2 ^= t[0];
            }
            (start2.elapsed(), acc2)
        };
        std::hint::black_box(acc);
        std::hint::black_box(t2.1);
        let ns_req = r.as_nanos() as f64 / iters as f64;
        let ns_resp = t2.0.as_nanos() as f64 / iters as f64;
        println!(
            "auth hot-path cost: request_tag={:.0} ns, response_tag={:.0} ns (release build)",
            ns_req, ns_resp
        );
        // Loose ceiling: a debug build is ~10x slower; this only catches a
        // pathological regression (e.g. an allocation or a syscall per tag).
        assert!(ns_req < 50_000.0, "request tag cost {ns_req} ns");
        assert!(ns_resp < 50_000.0, "response tag cost {ns_resp} ns");
    }
}
