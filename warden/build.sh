# build.sh — Build the warden in-VM agent (musl static binary).
# Usage:
#   ./build.sh              # Build warden → ../output/warden
#   ./build.sh --no-copy    # Build only (skip copy to ../output/)
# Generates src/version.rs from src/version.rs.in, then runs
# cargo build --release --target x86_64-unknown-linux-musl.

set -euo pipefail

WARDEN_ROOT="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$WARDEN_ROOT/.." && pwd)"

RED='\033[0;31m'
GREEN='\033[0;32m'
NC='\033[0m'

log() { echo -e "${GREEN}[==]${NC} $1"; }
err() { echo -e "${RED}[!!]${NC} $1"; exit 1; }

check_cmd() { command -v "$1" &>/dev/null || err "$1 not found — install it first"; }

# ── Prerequisites ──────────────────────────────────────────────────

check_cmd cargo
check_cmd rustup

ARCH="$(uname -m)"
TARGET="${ARCH}-unknown-linux-musl"

rustup target add "$TARGET" 2>/dev/null || true

cd "$WARDEN_ROOT"

# ── Generate src/version.rs ────────────────────────────────────────

COMMIT="$(git -C "$PROJECT_ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
if [ -n "$(git -C "$PROJECT_ROOT" status --porcelain --untracked-files=no 2>/dev/null)" ]; then
    COMMIT="${COMMIT}-dirty"
fi
VERSION_VAL="$(cat "$PROJECT_ROOT/VERSION" 2>/dev/null || echo 0.0.0-dev)"

# Content-stable generation: when every input except the wall clock is
# unchanged (same version, same commit), REUSE the existing file's
# BUILD_TIME so the regenerated bytes come out identical and the file is
# left untouched. A fresh timestamp on every invocation dirties warden/src
# whenever a row builds warden, which makes build.sh's freshness check
# mark warden + initramfs stale and the next gated row AUTO_REBUILDs
# everything — churning every artifact mtime and defeating cross-round
# reuse. The build time advances only when the code the
# binary describes actually changed.
# `|| true`: on a FRESH CHECKOUT src/version.rs does not exist yet (it is
# generated, never committed), and a missing file makes sed exit 2 — the
# plain command substitution then aborts the whole script under set -e
# (live: the release CI build). Empty output is the expected "no previous
# build time" answer, not an error.
rs_const() { sed -n "s/^pub const $1: &str = \"\\([^\"]*\\)\";/\\1/p" src/version.rs 2>/dev/null || true; }
BUILD_TIME="$(rs_const BUILD_TIME)"
if [ -z "$BUILD_TIME" ] \
   || [ "$(rs_const VERSION_COMMIT)" != "$COMMIT" ] \
   || [ "$(rs_const WARDEN_VERSION)" != "$VERSION_VAL" ]; then
    BUILD_TIME="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
fi

sed \
    -e "s|@WARDEN_NAME@|warden|g" \
    -e "s|@WARDEN_VERSION@|${VERSION_VAL}|g" \
    -e "s|@API_VERSION@|0.0.1|g" \
    -e "s|@BINDIR@|/usr/bin|g" \
    -e "s|@COMMIT@|${COMMIT}|g" \
    -e "s|@VERSION_COMMIT@|${COMMIT}|g" \
    -e "s|@BUILD_TIME@|${BUILD_TIME}|g" \
    src/version.rs.in > src/version.rs.new

if cmp -s src/version.rs.new src/version.rs; then
    rm -f src/version.rs.new
    log "src/version.rs unchanged (version=${VERSION_VAL}, commit=${COMMIT}) — kept as-is"
else
    mv src/version.rs.new src/version.rs
    log "Generated src/version.rs (version=${VERSION_VAL}, commit=${COMMIT})"
fi

# ── Unit tests (host target) ───────────────────────────────────────
# The unit suite MUST run before every build — nothing else executes it (no
# CI), so a broken/rotted test would otherwise be silently invisible while
# the binary keeps shipping. Root-gated #[ignore] tests (chroot/mount
# machinery) run too when we are root. Skip only for explicit scratch builds
# via WARDEN_SKIP_TESTS=1.

if [[ "${WARDEN_SKIP_TESTS:-0}" != "1" ]]; then
    log "Running unit tests (host target)..."
    cargo test --quiet
    if [[ "$(id -u)" == "0" ]]; then
        log "Running root-gated tests (#[ignore])..."
        cargo test --quiet -- --ignored
    else
        log "Not root — skipping root-gated (#[ignore]) tests"
    fi
else
    log "WARDEN_SKIP_TESTS=1 — skipping unit tests (scratch build)"
fi

# ── Build ──────────────────────────────────────────────────────────

cargo build --release --target "$TARGET"

# ── Copy to output/ ────────────────────────────────────────────────

if [[ "${1:-}" != "--no-copy" ]]; then
    mkdir -p "$PROJECT_ROOT/output"
    # Copy only on a content change: an unconditional cp stamps a fresh
    # mtime on output/warden on every build even when the binary is
    # byte-identical, which churns artifact identity and defeats reuse.
    if ! cmp -s "$WARDEN_ROOT/target/$TARGET/release/warden" "$PROJECT_ROOT/output/warden"; then
        cp "$WARDEN_ROOT/target/$TARGET/release/warden" "$PROJECT_ROOT/output/warden"
        log "Warden → output/warden"
    else
        log "output/warden already current — kept as-is"
    fi
fi
